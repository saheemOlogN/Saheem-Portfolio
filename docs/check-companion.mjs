import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import ts from 'typescript'
const source = await readFile(new URL('../src/components/companionDirector.ts', import.meta.url), 'utf8')
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText
const { CompanionDirector } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`)
const d = new CompanionDirector(() => 0)
assert.equal(d.mode, 'idle')
assert.equal(d.advance(11999), 'idle')
assert.equal(d.advance(1), '67')
assert.equal(d.advance(5999), '67')
assert.equal(d.advance(1), 'idle')
d.setSection('skills')
assert.equal(d.mode, 'gear5')
assert.equal(d.advance(60000), 'gear5', 'Gear 5 loops throughout Skills')
d.setSection('projects')
assert.equal(d.mode, 'idle')
d.setSection('skills')
assert.equal(d.mode, 'gear5', 'Revisiting Skills always retriggers Gear 5')
d.setSection('hero')
assert.equal(d.mode, 'idle', 'Returning to hero exits Gear 5')
d.advance(12000)
d.setSection('skills')
assert.equal(d.mode, 'gear5', 'Skills takes priority over a random special')
d.trigger('67')
assert.equal(d.advance(6000), 'gear5', 'Explicit special returns to active section mode')
const modes = new Set()
d.setSection('about')
for (let i=0;i<1000;i++) modes.add(d.advance(100))
assert.ok(modes.has('67') && modes.has('idle') && modes.has('dance'))
assert.ok(modes.size >= 3, 'Random rotation includes additional emotes')
d.trigger('thinking')
const thought=d.message
d.trigger('thinking')
assert.notEqual(d.message,thought,'Repeated interaction cycles dialogue')
for(const mode of ['dance','thinking','sleepy','celebrate']){d.trigger(mode);assert.equal(d.mode,mode);assert.ok(d.message);assert.equal(d.advance(6000),'idle')}
d.setSection('skills')
const gearLine=d.message
d.advance(8500)
assert.notEqual(d.message,gearLine,'Persistent Gear 5 dialogue rotates')
assert.equal(d.mode,'gear5')
console.log('Companion checks passed: seven emotes, dialogue rotation, random specials, interaction duration, Skills priority and return.')
